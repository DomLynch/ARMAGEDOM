-- ROLLBACK: supabase/down/20261024000008_arma_server_cash_down.sql.
-- A2 PR 2, server-granted money (docs/MULTIPLAYER-DATA-LAYER.md). The only way a character's money can rise is a kill the database settled:
-- arma_spawn_hit already writes one idempotent 'kill:<instance>:<generation>:<account>' event per paid contributor, and a trigger on that insert adds the
-- creature kind's payout to arma_cash.earned (a retried kill hits the event's primary key first, so it grants once). A save is then CLAMPED
-- (Lead's ruling: refusing would throw away real progress over cash, and in alpha trash kills stay per-phone): carried + bank is lowered to
-- start_cash_total + earned (or the total the run already holds, so a record stored before this migration can still be re-saved, never raised),
-- taking from carried first, then the bank. Every other field is stored as sent; the reply carries {clamped: true, carried, bank} for the phone to adopt.
-- Spending, dying (carried goes to 0) and banking only lower or move the total. NO bounty.
-- Limit (PR 3 / shop): spending is the client's word, so a phone can spend and later claim back up to the ceiling; it can never exceed it.

-- What a kill of a creature kind pays. Generated by server/data/generate-payout-seed.mjs (spawn kinds x marked.cashPerKill / bossCash).
create table public.arma_payout_rules (
  kind text primary key check (kind ~ '^[a-z0-9._:-]{1,64}$'),
  cash int not null check (cash between 0 and 1000000)
);
-- The server's lifetime tally of cash earned by this character.
create table public.arma_cash (
  character text primary key references public.arma_characters (id) on delete cascade,
  earned int not null default 0 check (earned between 0 and 1000000000)
);
alter table public.arma_payout_rules enable row level security;
alter table public.arma_cash enable row level security;
revoke all on public.arma_payout_rules, public.arma_cash from public, anon, authenticated;
insert into public.arma_config (key, value) values ('start_cash_total', '0'::jsonb), ('enforce_cash', 'true'::jsonb) on conflict (key) do nothing;

insert into public.arma_payout_rules (kind, cash) values
  ('boss-area7-knight', 200),
  ('boss-area8-veteran', 200),
  ('boss-butcher', 200),
  ('boss-south-nightborn', 200),
  ('boss-surgeon', 200),
  ('boss-warden', 200),
  ('boss-westminster-witch', 200),
  ('giant-salamander', 100),
  ('hollow-scavenger', 100),
  ('low-hover-drone', 100),
  ('original-dog', 100),
  ('original-rat', 100),
  ('original-roach', 100),
  ('original-wolf', 100)
on conflict (kind) do update set cash = excluded.cash;

create function public.arma_grant_kill_cash() returns trigger language plpgsql security definer set search_path = '' as $$
declare pay int;
begin
  if new.character is null or new.event_id not like 'kill:%' then return new; end if;
  select cash into pay from public.arma_payout_rules where kind = new.payload ->> 'kind';
  if coalesce(pay, 0) > 0 then
    insert into public.arma_cash (character, earned) values (new.character, pay)
      on conflict (character) do update set earned = least(public.arma_cash.earned + excluded.earned, 1000000000);
  end if;
  return new;
end $$;
create trigger arma_events_grant_cash after insert on public.arma_events for each row when (new.kind = 'kill') execute function public.arma_grant_kill_cash();

-- The most carried + bank a save of this character may hold: what the server granted, or what the stored run already holds (the larger). null = not enforced.
create function public.arma_cash_ceiling(p_character text) returns numeric language plpgsql stable security definer set search_path = '' as $$
declare allowed numeric; held numeric;
begin
  if not coalesce((select value = 'true'::jsonb from public.arma_config where key = 'enforce_cash'), true) then return null; end if;
  allowed := coalesce((select (value #>> '{}')::numeric from public.arma_config where key = 'start_cash_total'), 0)
           + coalesce((select earned from public.arma_cash where character = p_character), 0);
  held := coalesce((select coalesce((record #>> '{marked,carried}')::numeric, 0) + coalesce((record #>> '{marked,bank}')::numeric, 0) from public.arma_runs where character = p_character), 0);
  return greatest(allowed, held);
end $$;

-- arma_save_run as 000007 made it, plus the clamp after the record check. A clamped save is stored with the lowered numbers and answers
-- {revision, savedAt, clamped: true, carried, bank}; that answer is what a retry of the same save gets back.
create or replace function public.arma_save_run(p_account uuid, p_character text, p_era int, p_record jsonb, p_expected_revision int, p_seq int) returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.arma_runs; lo int; hi int; why text; h text; answer jsonb; existed boolean; rec jsonb := p_record; ceiling numeric; carried numeric; bank numeric; excess numeric;
begin
  if not public.arma_allowed(p_account) then raise exception 'arma is not open for this account' using errcode = 'O0007'; end if;
  if not public.arma_owns(p_character, p_account) then raise exception 'not this account''s character' using errcode = 'O0007'; end if;
  if p_seq is null or p_seq < 1 then return jsonb_build_object('refused', 'seq'); end if;
  h :=encode(sha256(convert_to(p_era::text || ':' || p_expected_revision::text || ':' || coalesce(p_record::text, ''), 'UTF8')), 'hex');
  select * into r from public.arma_runs where character = p_character for update;
  existed := found; -- FOUND is reset by every later SELECT INTO
  if existed then
    if p_seq = r.last_seq then
      if r.last_hash = h then return r.last_result || jsonb_build_object('replayed', true); end if;
      return jsonb_build_object('refused', 'seq-conflict', 'lastSeq', r.last_seq);
    end if;
    if p_seq < r.last_seq then return jsonb_build_object('refused', 'stale-seq', 'lastSeq', r.last_seq); end if;
  end if;
  select (value #>> '{}')::int into lo from public.arma_config where key = 'oldest_era';
  select (value #>> '{}')::int into hi from public.arma_config where key = 'current_era';
  if p_era < lo or p_era > hi then return jsonb_build_object('refused', 'era', 'currentEra', hi); end if;
  if jsonb_typeof(p_record) <> 'object' or (p_record ->> 'version') is distinct from p_era::text then return jsonb_build_object('refused', 'shape'); end if;
  if not existed then
    if p_expected_revision <> 0 then return jsonb_build_object('refused', 'stale', 'revision', 0); end if;
  elsif p_expected_revision <> r.revision then
    return jsonb_build_object('refused', 'stale', 'revision', r.revision);
  end if;
  why := public.arma_check_record(p_record);
  if why is not null then return jsonb_build_object('refused', split_part(why, ':', 1), 'reason', why); end if;
  -- The clamp: only the two money numbers change, carried first, then the bank.
  ceiling := public.arma_cash_ceiling(p_character);
  carried := coalesce((p_record #>> '{marked,carried}')::numeric, 0);
  bank := coalesce((p_record #>> '{marked,bank}')::numeric, 0);
  if ceiling is not null and carried + bank > ceiling then
    excess := carried + bank - ceiling;
    bank := bank - greatest(excess - carried, 0);
    carried := greatest(carried - excess, 0);
    rec := jsonb_set(jsonb_set(rec, '{marked,carried}', to_jsonb(carried::bigint)), '{marked,bank}', to_jsonb(bank::bigint));
  else
    ceiling := null; -- not clamped
  end if;
  if not existed then
    begin
      insert into public.arma_runs (character, era, record) values (p_character, p_era, rec) returning * into r;
    exception when unique_violation then
      -- A concurrent first save won the race: this phone is stale, not broken.
      return jsonb_build_object('refused', 'stale', 'revision', 1);
    end;
  else
    update public.arma_runs set era = p_era, record = rec, revision = r.revision + 1, saved_at = now() where character = p_character returning * into r;
  end if;
  answer := jsonb_build_object('revision', r.revision, 'savedAt', r.saved_at);
  if ceiling is not null then answer := answer || jsonb_build_object('clamped', true, 'carried', carried, 'bank', bank); end if;
  update public.arma_runs set last_seq = p_seq, last_hash = h, last_result = answer where character = p_character;
  return answer;
end $$;

-- Internal like arma_check_record: nothing is granted. The trigger function runs as the table owner; no role calls it.
revoke all on function public.arma_cash_ceiling(text), public.arma_grant_kill_cash() from public, anon, authenticated;
commit;
