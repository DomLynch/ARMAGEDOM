-- A2 PR 3b, REPORT-ONLY ownership (Lead's ruling for alpha: never delete a legitimately earned weapon; not every boss kill is server-settled yet).
-- A save whose record says an always-drop weapon is "owned" while the character has no arma_loot receipt for that item is STORED EXACTLY AS SENT.
-- The reply gains {unreceipted: [record paths]}, and a server-side counter row per character + item is bumped (no client-visible penalty). The counter
-- tells us whether enforcement is safe: it switches on (follow-up "A") once every boss kill settles on the server and Combat has confirmed the
-- not-owned shape ('eligible'). Nothing here changes, drops or rewrites any byte of a save.

-- Where the save record keeps each always-drop weapon and the loot item that is its receipt. Generated by server/data/generate-item-sources-seed.mjs
-- from the game's own validated content.
create table public.arma_item_sources (
  path text primary key check (path ~ '^[A-Za-z]+(\.[A-Za-z]+)?$'),
  item text not null unique check (item ~ '^[a-z0-9._:-]{1,120}$')
);
insert into public.arma_item_sources (path, item) values
