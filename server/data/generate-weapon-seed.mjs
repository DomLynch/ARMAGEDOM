// node server/data/generate-weapon-seed.mjs > supabase/migrations/<next number>_arma_weapon_rules_seed.sql
// Writes the SQL that seeds arma_weapon_rules from the game's own tables (Combat's weaponRules() with the progression ceiling), so the
// migration is generated, never typed. Needs the Web tree and its node_modules. When the game data changes, generate the next migration
// (an upsert, so re-applying only moves the numbers); Web/tests/arma-weapon-rules-seed.test.js fails until you do.
import fs from "node:fs";
import { seedWeaponRows } from "./world-rows.js";
import { weaponRules } from "../../Web/src/engine/world-events.js";

const content = JSON.parse(fs.readFileSync(new URL("../../Web/public/world/area-content.json", import.meta.url), "utf8"));
const rows = seedWeaponRows(weaponRules(), content.progression);
process.stdout.write(`begin;
-- Generated by server/data/generate-weapon-seed.mjs from Web/src/engine/world-events.js weaponRules() and the progression rows of
-- Web/public/world/area-content.json: damage = base x the largest progression multiplier (a fully mastered hit is inside it).
-- Player weapons only: creature attacks (teeth, bolt) get no row, so a claim of one is refused by arma_spawn_hit ('weapon').
insert into public.arma_weapon_rules (weapon, max_damage_per_hit, max_hits_per_s) values
${rows.map(([weapon, damage, rate]) => `  ('${weapon}', ${damage}, ${rate})`).join(",\n")}
on conflict (weapon) do update set max_damage_per_hit = excluded.max_damage_per_hit, max_hits_per_s = excluded.max_hits_per_s;
commit;
`);
